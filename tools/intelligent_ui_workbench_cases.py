"""Input-driven workbench regressions, reused by every deployment/browser mode.
Provider transport is never configured. Programmatic setup only supplies fixtures
or simulates trusted project/task lifecycle events; editing uses actual controls.
"""
import json


def run_workbench_cases(browser, mode, load, check, passed, report):
    page = load(browser, mode)
    page.evaluate('()=>{window.workbenchPanel=vb6Studio.intelligentUI.open();}')
    editor = page.get_by_label('Intelligent UI editor', exact=True)
    data = page.get_by_label('Intelligent UI JSON data', exact=True)
    preview = page.locator('.iui-playground-preview')
    def button(name):
        root = page if name in ['Cancel','Discard draft','Queue reviewed message'] else page.locator('.iui-workbench')
        return root.get_by_role('button', name=name, exact=True)
    def rendered(): page.wait_for_function('workbenchPanel.renderedRevision===workbenchPanel.model.active?.revision && !!workbenchPanel.surface?.result')
    def success(name): passed(mode + ': workbench ' + name)
    rendered()
    original = page.evaluate('workbenchPanel.model.activeId')
    preview.locator('input[type=range]').fill('12')
    page.wait_for_function('document.querySelector(".iui-playground-preview .iui-metric-value")?.textContent==="348"')
    button('New document').click()
    editor.fill('<metric label="Draft metric" value={data.value}/><text>Draft</text>')
    data.fill('{"value":42}')
    rendered()
    check(preview.locator('.iui-metric-value').inner_text() == '42', 'JSON data did not reach the preview')
    draft = page.evaluate('workbenchPanel.model.activeId')
    page.get_by_label('UI document title', exact=True).fill('Working draft')
    editor.focus()
    rendered()
    success('source and JSON editors render a separate named draft')
    page.get_by_label('Intelligent UI document', exact=True).select_option(original)
    rendered()
    check(preview.locator('input[type=range]').input_value() == '12', 'Switch lost original calculator state')
    page.get_by_label('Intelligent UI document', exact=True).select_option(draft)
    rendered()
    check('Draft metric' in editor.input_value(), 'Switch lost draft source')
    check(json.loads(data.input_value()) == {'value':42}, 'Switch lost JSON data')
    success('document switching keeps independent source, JSON and interactive state')
    button('Duplicate document').click()
    rendered()
    check(page.evaluate('workbenchPanel.model.activeId') != draft, 'Duplicate reused original identity')
    editor.fill('<text>Replaced copy</text>')
    rendered()
    button('Undo').click()
    rendered()
    check('Draft metric' in editor.input_value(), 'Undo did not restore source')
    button('Redo').click()
    rendered()
    check(editor.input_value() == '<text>Replaced copy</text>', 'Redo did not restore source')
    check(page.evaluate('workbenchPanel.model.documents.get('+json.dumps(draft)+').source').startswith('<metric'), 'Copy changed original draft')
    success('duplicate isolation and document-level undo/redo')
    editor.fill('<text>{data.value}</text>')
    rendered()
    data.fill('{invalid')
    page.wait_for_function('document.querySelector(".iui-workbench-notice").textContent.includes("Invalid preview JSON")')
    check(preview.locator('.iui-text').inner_text() == '42', 'Invalid JSON destroyed last good rendering')
    data.fill('{"value":43}')
    rendered()
    button('Format JSON').click()
    rendered()
    check('\n' in data.input_value() and json.loads(data.input_value())['value']==43, 'JSON formatting failed')
    success('invalid JSON preserves the last valid view and corrections recover')
    page.get_by_label('Live UI preview', exact=True).uncheck()
    editor.fill('<text>Manual render</text>')
    check(preview.locator('.iui-text').inner_text() == '43', 'Manual preview updated automatically')
    button('Render').click()
    rendered()
    check(preview.locator('.iui-text').inner_text() == 'Manual render', 'Manual Render failed')
    page.get_by_label('Live UI preview', exact=True).check()
    success('manual/live rendering modes')
    editor.fill('<text>alpha alpha</text>')
    rendered()
    page.get_by_label('Find in UI source', exact=True).fill('alpha')
    button('Find next').click()
    check(page.evaluate('workbenchPanel.source.value.slice(workbenchPanel.source.selectionStart,workbenchPanel.source.selectionEnd)')=='alpha','Find did not select source')
    page.get_by_label('Replace in UI source', exact=True).fill('beta')
    button('Replace all').click()
    rendered()
    check(editor.input_value()=='<text>beta beta</text>', 'Literal replace all failed')
    button('Undo').click()
    rendered()
    check(editor.input_value()=='<text>alpha alpha</text>', 'Replace all was not a single undo transaction')
    success('literal find/replace with transactional undo')
    page.get_by_label('UI preview viewport', exact=True).select_option('375')
    page.wait_for_function('workbenchPanel.surface.viewportSize.width===375')
    check(round(preview.bounding_box()['width'])==375, 'Phone preview does not have the selected width')
    page.get_by_label('UI preview viewport', exact=True).select_option('auto')
    success('fixed-width and responsive viewport presets')
    with page.expect_download() as capture:
        button('Export document').click()
    downloaded = capture.value
    target = report / (mode+'-workbench-export.json')
    downloaded.save_as(target)
    exported = json.loads(target.read_text())
    check(set(exported)=={'format','version','title','source','dataText'}, 'Export included context, state or grants')
    check(exported['source']==editor.input_value(), 'Export lost exact source')
    page.get_by_label('Import Intelligent UI document', exact=True).set_input_files({'name':'roundtrip.iui.json','mimeType':'application/json','buffer':target.read_bytes()})
    rendered()
    check(editor.input_value()==exported['source'] and data.input_value()==exported['dataText'], 'Import did not restore source/JSON')
    check(not page.evaluate('workbenchPanel.model.dirty()'), 'Unchanged imported document is dirty')
    success('download and file-input roundtrip contains source/data only')
    imported=page.evaluate('workbenchPanel.model.activeId')
    button('Close document').click()
    page.wait_for_function('!workbenchPanel.model.documents.has('+json.dumps(imported)+')')
    check(page.get_by_role('button',name='Discard draft',exact=True).count()==0, 'Clean import asked to discard')
    page.get_by_label('Import Intelligent UI document', exact=True).set_input_files({'name':'example.dil','mimeType':'text/plain','buffer':b'<text>Imported DIL</text>'})
    rendered()
    check(preview.locator('.iui-text').inner_text()=='Imported DIL', 'Plain DIL import failed')
    before=page.evaluate('workbenchPanel.model.documents.size')
    page.get_by_label('Import Intelligent UI document', exact=True).set_input_files({'name':'invalid.json','mimeType':'application/json','buffer':b'{"format":"other","version":1}'})
    page.wait_for_function('document.querySelector(".iui-workbench-notice").textContent.includes("Unsupported")')
    check(page.evaluate('workbenchPanel.model.documents.size')==before, 'Invalid import partially added a document')
    success('clean close, plain DIL import and atomic invalid-file rejection')
    current=page.evaluate('workbenchPanel.model.activeId')
    button('Close document').click()
    button('Cancel').last.click()
    check(page.evaluate('workbenchPanel.model.activeId')==current,'Cancelled discard removed draft')
    button('Close document').click()
    # An external model edit while a confirmation is visible must defeat stale consent.
    page.evaluate('workbenchPanel.model.edit({source:"<text>Changed during confirmation</text>"})')
    button('Discard draft').click()
    page.wait_for_function('document.querySelector(".iui-workbench-notice").textContent.includes("changed during confirmation")')
    check(page.evaluate('workbenchPanel.model.activeId')==current,'Stale confirmation discarded changed source')
    success('cancelled and stale discard confirmations preserve drafts')
    source='<button onClick={() => GenUI.issueNewTurn("Workbench reviewed message")}>Review workbench action</button>'
    editor.fill(source)
    rendered()
    preview.get_by_role('button',name='Review workbench action',exact=True).click()
    button('Queue reviewed message').wait_for()
    page.evaluate('workbenchPanel.model.edit({source:"<text>New source</text>"})')
    button('Queue reviewed message').wait_for(state='detached')
    rendered()
    check(page.evaluate('vb6Studio.codingAgents.conversations.active.followups.items.length')==0,'Source change queued a cancelled review')
    success('editing source actively closes pending review without queuing')
    editor.fill(source)
    rendered()
    preview.get_by_role('button',name='Review workbench action',exact=True).click()
    button('Queue reviewed message').wait_for()
    page.evaluate('vb6Studio.intelligentUI.setEnabled(false)')
    button('Queue reviewed message').wait_for(state='detached')
    page.wait_for_function('!workbenchPanel.surface && !document.querySelector(".iui-playground-preview .iui-root")')
    check(not editor.is_disabled(), 'Disabling UI also disabled source editing')
    page.evaluate('vb6Studio.intelligentUI.setEnabled(true)')
    rendered()
    oldtask=page.evaluate('vb6Studio.codingAgents.conversations.activeId')
    page.evaluate('vb6Studio.codingAgents.conversations.create("Workbench second task")')
    rendered()
    preview.get_by_role('button',name='Review workbench action',exact=True).click()
    button('Queue reviewed message').click()
    check(page.evaluate('vb6Studio.codingAgents.conversations.active.followups.items.at(-1).text')=='Workbench reviewed message','Preview did not bind to new task')
    check(page.evaluate('vb6Studio.codingAgents.conversations.tasks.get('+json.dumps(oldtask)+').followups.items.length')==0,'Review crossed task ownership')
    success('disable releases previews and task switch binds new actions to the new owner')
    page.evaluate('''async()=>{const a=vb6Studio.mcp.adapter;a.setEnabled(true);window.galleryResult=await a.tools.find(t=>t.name==='vb6.ui.present').execute({title:'Gallery fixture',source:'{@body const [n,setN]=DIL.useState(3)}<slider label="Gallery slider" min={1} max={10} value={n} onChange={v=>setN(v)}/><metric label="Gallery metric" value={n}/>'},{principal:'workbench-browser'});}''')
    gallery=page.locator('.iui-gallery-item').filter(has_text='Gallery fixture')
    gallery.get_by_role('slider',name='Gallery slider',exact=True).fill('7')
    page.wait_for_function('document.querySelector(".iui-gallery .iui-metric-value")?.textContent==="7"')
    page.get_by_label('Filter live UI documents',exact=True).fill('missing title')
    page.wait_for_function('[...workbenchPanel.galleryView.items.values()].every(i=>!i.surface)')
    page.get_by_label('Filter live UI documents',exact=True).fill('Gallery')
    gallery.get_by_role('slider',name='Gallery slider',exact=True).wait_for()
    check(gallery.get_by_role('slider',name='Gallery slider',exact=True).input_value()=='7','Filtering lost gallery state')
    gallery.locator(':scope > summary').click()
    page.wait_for_function('[...workbenchPanel.galleryView.items.values()].every(i=>!i.surface)')
    gallery.locator(':scope > summary').click()
    check(gallery.get_by_role('slider',name='Gallery slider',exact=True).input_value()=='7','Collapsing lost gallery state')
    gallery.get_by_role('button',name='Edit a local copy',exact=True).click()
    rendered()
    check('Gallery slider' in editor.input_value(),'Edit local copy did not copy source')
    gallery.get_by_role('button',name='Close UI document',exact=True).click()
    gallery.wait_for(state='detached')
    check('Gallery slider' in editor.input_value(),'Closing remote UI removed local draft')
    success('gallery filter/collapse release renderers and preserve state; copied drafts are independent')
    preview.get_by_role('slider',name='Gallery slider',exact=True).fill('9')
    page.wait_for_function('document.querySelector(".iui-playground-preview .iui-metric-value")?.textContent==="9"')
    page.evaluate('vb6Studio.documents.closeTool("tool:intelligent-ui")')
    page.wait_for_selector('.iui-workbench',state='detached')
    page.evaluate('()=>{window.workbenchPanel=vb6Studio.intelligentUI.open();}')
    rendered()
    check(preview.get_by_role('slider',name='Gallery slider',exact=True).input_value()=='9','Closing panel lost in-memory preview state')
    page.evaluate('''()=>{window.oldUIContext=vb6Studio.intelligentUI.contextRevision;vb6Studio.loadProject(JSON.parse(JSON.stringify(vb6Studio.project)));}''')
    page.wait_for_function('vb6Studio.intelligentUI.contextRevision>oldUIContext')
    page.evaluate('()=>{window.workbenchPanel=vb6Studio.intelligentUI.open();}')
    rendered()
    check(preview.get_by_role('slider',name='Gallery slider',exact=True).input_value()=='3','Workspace change restored revoked runtime state')
    success('panel reopening retains drafts/state; project-session change resets live state')
    page.screenshot(path=str(report/(mode+'-workbench.png')))
    check(not page._errors,'Uncaught workbench errors: '+repr(page._errors))
    check(page.evaluate('vb6Studio.codingAgents.agent.usage.requests')==0,'Workbench unexpectedly contacted a provider')
    success('no uncaught browser errors or provider requests')
    page.close()
