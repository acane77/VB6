function build(char) {
  if (char==='\u00a0') char=' ';
  const [base, ...marks] = char.normalize('NFD');
  const recipe = recipes[char] || recipes[base];
  if (!recipe || (!recipes[char] && marks.some(mark=>!accents.has(mark)))) return null;
  const mask = new Uint8Array(128), accented=!recipes[char] && marks.length>0;
  const hasTop=accented && marks.some(mark=>!['\u0327','\u0328'].includes(mark));
  const stroke = textStrokes[char] || textStrokes[base];
  if(stroke){
    const top=hasTop?3:2, height=hasTop?11:12;
    for(let y=0;y<height;y++){
      const row=Math.min(8,Math.floor(y*9/height)),bits=parseInt(stroke.slice(row*2,row*2+2),16);
      for(let x=0;x<6;x++)if(bits & (32>>x))mask[(y+top)*8+x+1]=1;
    }
  }else for(let row=0;row<7;row++) {
    const bits=parseInt(recipe.slice(row*2,row*2+2),16),top=hasTop?3:2,height=hasTop?11:12;
    for(let y=Math.floor(row*height/7);y<Math.floor((row+1)*height/7);y++)
      for(let x=0;x<6;x++)if(bits & (16>>Math.floor(x*5/6)))mask[(y+top)*8+x+1]=1;
  }
  if(accented) for(const mark of marks) for(const [x,y] of accents.get(mark)) mask[y*8+x]=1;
  return mask;
}
/** The returned mask is immutable by convention and never exposed publicly. */
export function letterformMask(code) {
  if(!Number.isInteger(code)||code<32||code>0x10ffff)return null;
  // Braille: 2 columns x 4 dots, with the Unicode dot numbering, not row-major.
  if(code>=0x2800&&code<=0x28ff) {
    const mask=new Uint8Array(128),bits=code-0x2800,points=[[1,1],[1,5],[1,9],[5,1],[5,5],[5,9],[1,13],[5,13]];
    for(let n=0;n<8;n++)if(bits&(1<<n)){const [x,y]=points[n];mask[y*8+x]=mask[y*8+x+1]=mask[(y+1)*8+x]=mask[(y+1)*8+x+1]=1;}
    return mask;
  }
  if(cache.has(code))return cache.get(code);
  const mask=build(String.fromCodePoint(code));
  if(cache.size>=512)cache.delete(cache.keys().next().value);
  cache.set(code,mask);return mask;
}
